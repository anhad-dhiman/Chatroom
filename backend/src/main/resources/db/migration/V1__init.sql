CREATE TABLE users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      VARCHAR(32)  NOT NULL,
    display_name  VARCHAR(64)  NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    avatar_color  VARCHAR(16)  NOT NULL,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT ux_users_username UNIQUE (username)
);

CREATE TABLE conversations (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type            VARCHAR(16) NOT NULL,
    name            VARCHAR(64),
    description     VARCHAR(255),
    -- "smallerUserId:largerUserId" for direct messages, guarantees one DM per pair
    direct_key      VARCHAR(64),
    created_by      BIGINT REFERENCES users (id) ON DELETE SET NULL,
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    last_message_at TIMESTAMP WITH TIME ZONE,
    CONSTRAINT ux_conversations_name UNIQUE (name),
    CONSTRAINT ux_conversations_direct_key UNIQUE (direct_key)
);

CREATE TABLE conversation_members (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id      BIGINT NOT NULL REFERENCES conversations (id) ON DELETE CASCADE,
    user_id              BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    last_read_message_id BIGINT NOT NULL DEFAULT 0,
    joined_at            TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT ux_conversation_members UNIQUE (conversation_id, user_id)
);
CREATE INDEX ix_conversation_members_user ON conversation_members (user_id);

CREATE TABLE messages (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id BIGINT NOT NULL REFERENCES conversations (id) ON DELETE CASCADE,
    sender_id       BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    content         VARCHAR(2000) NOT NULL,
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    edited_at       TIMESTAMP WITH TIME ZONE,
    deleted         BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE INDEX ix_messages_conversation_id ON messages (conversation_id, id);

CREATE TABLE message_reactions (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    message_id BIGINT NOT NULL REFERENCES messages (id) ON DELETE CASCADE,
    user_id    BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    emoji      VARCHAR(16) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT ux_message_reactions UNIQUE (message_id, user_id, emoji)
);
